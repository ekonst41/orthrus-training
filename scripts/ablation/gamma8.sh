#!/usr/bin/env bash
# Абляция: обучение Orthrus с весами позиций блока, gamma = 8, затем итоговая оценка.
#
#   Вес токена на позиции i блока = exp(-i/8): первый токен 1.0, 8-й 0.42, 16-й 0.15.
#   На первые 8 позиций приходится 65% веса лосса (при равных весах — 26%).
#   Умеренный акцент: начало блока в приоритете, хвост ещё заметно обучается.
#
# Запуск:   bash scripts/ablation/gamma8.sh [GPU]
#           GPU — номер видеокарты (0, 1, ...; см. nvidia-smi), по умолчанию 0.
# Фоном:    nohup bash scripts/ablation/gamma8.sh 0 > logs/gamma8.log 2>&1 &
# Длится:   ~29 ч на A100 80GB (2 эпохи, 3920 шагов); H100 быстрее.
# Прервали: запустите ту же команду ещё раз — обучение продолжится с последнего чекпойнта.
set -euo pipefail
source "$(dirname "$0")/common.sh"

GAMMA=8
GPU=${1:-0}
shift || true # остальные аргументы (section.key=value) — дополнительные настройки

train_and_evaluate "$GAMMA" "$GPU" "$@"
