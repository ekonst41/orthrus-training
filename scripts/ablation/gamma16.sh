#!/usr/bin/env bash
# Абляция: обучение Orthrus с весами позиций блока, gamma = 16, затем итоговая оценка.
#
#   Вес токена на позиции i блока = exp(-i/16): первый токен 1.0, 8-й 0.65, 16-й 0.39.
#   На первые 8 позиций приходится 46% веса лосса (при равных весах — 26%).
#   Мягкий акцент: масштаб DFlash (gamma 7 при блоке 16), перенесённый на наш блок K=32.
#
# Запуск:   bash scripts/ablation/gamma16.sh [GPU]
#           GPU — номер видеокарты (0, 1, ...; см. nvidia-smi), по умолчанию 0.
# Фоном:    nohup bash scripts/ablation/gamma16.sh 0 > logs/gamma16.log 2>&1 &
# Длится:   ~29 ч на A100 80GB (2 эпохи, 3920 шагов); H100 быстрее.
# Прервали: запустите ту же команду ещё раз — обучение продолжится с последнего чекпойнта.
set -euo pipefail
source "$(dirname "$0")/common.sh"

GAMMA=16
GPU=${1:-0}
shift || true # остальные аргументы (section.key=value) — дополнительные настройки

train_and_evaluate "$GAMMA" "$GPU" "$@"
